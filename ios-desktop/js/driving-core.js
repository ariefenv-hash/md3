  // ---------- 题库运行时归一（生成器已严格校验；此处为运行时防线 + 测试锚） ----------
  /**
   * normalizeBank(raw)：畸形条目剔除不抛错。
   * 规则：id 字符串非空；s ∈ {1,4}；type ∈ QTYPE；题干/解析非空；
   *   single/judge 选项 2-4 且 ans 界内；multi 选项 3-4 且 ans 为升序去重数组（≥2 项）；
   *   img 缺省 null，存在时必须命中 SIGN_SHAPES；id 重复剔除后者。
   */
  function normalizeBank(raw) {
    var out = [], seen = {};
    if (!Array.isArray(raw)) return out;
    for (var i = 0; i < raw.length; i++) {
      var r = raw[i];
      if (!r || typeof r !== 'object' || Array.isArray(r)) continue;
      var id = typeof r.id === 'string' ? r.id.trim() : '';
      if (!id || seen[id]) continue;
      var s = r.s;
      if (s !== 1 && s !== 4) continue;
      var type = r.type;
      if (type !== QTYPE.JUDGE && type !== QTYPE.SINGLE && type !== QTYPE.MULTI) continue;
      var qs = typeof r.q === 'string' ? r.q.trim() : '';
      var exp = typeof r.exp === 'string' ? r.exp.trim() : '';
      if (!qs || !exp) continue;
      var opts = Array.isArray(r.opts) ? r.opts.slice(0, 4) : null;
      if (!opts) continue;
      var ok = true, j;
      for (j = 0; j < opts.length; j++) {
        if (typeof opts[j] !== 'string' || !opts[j].trim()) { ok = false; break; }
        opts[j] = opts[j].trim();
      }
      if (!ok) continue;
      var ans = r.ans, ansOk = false;
      if (type === QTYPE.MULTI) {
        ansOk = Array.isArray(ans) && ans.length >= 2 && ans.length <= opts.length;
        if (ansOk) {
          var norm = [];
          for (j = 0; j < ans.length; j++) {
            if (typeof ans[j] !== 'number' || !isFinite(ans[j]) || ans[j] < 0 || ans[j] >= opts.length || ans[j] % 1 !== 0) { ansOk = false; break; }
            if (norm.indexOf(ans[j]) < 0) norm.push(ans[j]);
          }
          if (ansOk) {
            norm.sort(function (a, b) { return a - b; });
            if (norm.length < 2) ansOk = false;   // 去重后不足两项 → 非多选
            else ans = norm;
          }
        }
      } else {
        ansOk = typeof ans === 'number' && isFinite(ans) && ans % 1 === 0 && ans >= 0 && ans < opts.length;
      }
      if (!ansOk) continue;
      var img = r.img == null ? null : r.img;
      if (img !== null && !SIGN_SHAPES[img]) continue;
      seen[id] = true;
      out.push({ id: id, s: s, cat: String(r.cat || '').slice(0, 12), type: type, q: qs, opts: opts, ans: ans, exp: exp.slice(0, 600), img: img });
    }
    return out;
  }

  /** 科目过滤（s=1|4，畸形输入返回空数组） */
  function bankFor(bank, s) {
    if (!Array.isArray(bank)) return [];
    if (s !== 1 && s !== 4) return [];
    return bank.filter(function (b) { return b.s === s; });
  }

  /** 题目合法性自检（normalizeBank 之后应为恒真——页面侧断言用） */
  function isValidQuestion(q) {
    if (!q || typeof q !== 'object') return false;
    if (!q.id || (q.s !== 1 && q.s !== 4)) return false;
    if (!q.q || !q.exp) return false;
    if (!Array.isArray(q.opts) || q.opts.length < 2) return false;
    if (q.type === QTYPE.MULTI) {
      return Array.isArray(q.ans) && q.ans.length >= 2 &&
        q.ans.every(function (i) { return i >= 0 && i < q.opts.length; });
    }
    if (q.type !== QTYPE.JUDGE && q.type !== QTYPE.SINGLE) return false;
    return typeof q.ans === 'number' && q.ans >= 0 && q.ans < q.opts.length;
  }

  // ---------- 判分 ----------
  /**
   * 答案校验（纯函数）：single/judge 比对索引；multi 集合相等（有序数组）。
   * picked 形态：single/judge → number；multi → number 数组。畸形一律 false。
   */
  function isCorrect(q, picked) {
    if (!isValidQuestion(q)) return false;
    if (q.type === QTYPE.MULTI) {
      if (!Array.isArray(picked)) return false;
      var a = q.ans.slice().sort(function (x, y) { return x - y; });
      var p = picked.filter(function (i) { return typeof i === 'number' && i % 1 === 0 && i >= 0 && i < q.opts.length; });
      if (p.length !== a.length) return false;
      p.sort(function (x, y) { return x - y; });
      for (var i = 0; i < a.length; i++) if (a[i] !== p[i]) return false;
      return true;
    }
    return typeof picked === 'number' && picked % 1 === 0 && picked === q.ans;
  }

  // ---------- 组卷 ----------
  /** Fisher-Yates 洗牌（rng 注入——测试用种子随机，页面用 Math.random） */
  function shuffle(list, rng) {
    var a = Array.isArray(list) ? list.slice() : [];
    var rand = typeof rng === 'function' ? rng : Math.random;
    for (var i = a.length - 1; i > 0; i--) {
      var j = Math.floor(rand() * (i + 1));
      if (j < 0 || j >= a.length) j = i;
      var t = a[i]; a[i] = a[j]; a[j] = t;
    }
    return a;
  }

  /**
   * 模拟考组卷：科目题库洗牌后取前 count（题库不足时封顶题库长度）。
   * 题目引用同一对象（浅拷贝列表，不复制题体）。
   */
  function pickExam(bank, s, rng) {
    var pool = bankFor(bank, s);
    var spec = examSpec(s);
    return shuffle(pool, rng).slice(0, Math.min(spec.count, pool.length));
  }

  /** 模拟考规格（畸形科目回落科目一；深拷贝防改写） */
  function examSpec(s) {
    var spec = EXAM_SPEC[s] || EXAM_SPEC[1];
    return { count: spec.count, minutes: spec.minutes, per: spec.per, pass: spec.pass };
  }

  /**
   * 交卷判分：answers[i] = 第 i 题用户作答（null=未答）。
   * 返回 { total, answered, correct, wrong, score, full, pass, per }（per[i]=bool）。
   */
  function gradeExam(questions, answers) {
    var per = [], correct = 0, answered = 0;
    if (!Array.isArray(questions)) questions = [];
    for (var i = 0; i < questions.length; i++) {
      var ok = isCorrect(questions[i], answers ? answers[i] : null);
      per.push(ok);
      if (ok) correct++;
      if (answers && answers[i] !== null && answers[i] !== undefined &&
          (questions[i].type === QTYPE.MULTI ? Array.isArray(answers[i]) : typeof answers[i] === 'number')) answered++;
    }
    var spec = examSpec(questions.length && questions[0] ? questions[0].s : 1);
    var score = correct * spec.per;
    return {
      total: questions.length,
      answered: answered,
      correct: correct,
      wrong: questions.length - correct,
      score: score,
      full: questions.length * spec.per,
      pass: score >= spec.pass,
      per: per,
    };
  }

  // ---------- 模拟考计时（墙钟锚定——后台/回前台不漂移） ----------
  /**
   * 剩余毫秒（纯函数）：deadline - now，钳 0。now 缺省 Date.now()。
   * 计时显示层每 tick 用 now 重算（不递减计数器），后台节流/挂起天然不漂移。
   */
  function examRemaining(startTs, minutes, now) {
    var start = (typeof startTs === 'number' && isFinite(startTs) && startTs > 0) ? startTs : 0;
    var mins = (typeof minutes === 'number' && isFinite(minutes) && minutes > 0) ? minutes : 0;
    var n = (typeof now === 'number' && isFinite(now) && now >= 0) ? now : Date.now();
    return Math.max(0, start + mins * 60 * 1000 - n);
  }

  /** 已用毫秒（成绩页「用时」展示；start 倒挂钳 0） */
  function examElapsed(startTs, now) {
    var start = (typeof startTs === 'number' && isFinite(startTs) && startTs > 0) ? startTs : 0;
    var n = (typeof now === 'number' && isFinite(now) && now >= 0) ? now : Date.now();
    return Math.max(0, n - start);
  }

  /** mm:ss 倒计时展示（向上取整秒——剩 1ms 也显示 00:01 不跳 00:00） */
  function fmtClock(ms) {
    var v = (typeof ms === 'number' && isFinite(ms) && ms > 0) ? ms : 0;
    var total = Math.min(5999, Math.ceil(v / 1000));
    var m = Math.floor(total / 60), s = total % 60;
    return (m < 10 ? '0' + m : '' + m) + ':' + (s < 10 ? '0' + s : '' + s);
  }

  // ---------- 错题本（艾宾浩斯同构 #28：阶 s + 日键 due） ----------
  function pad2(n) { return n < 10 ? '0' + n : '' + n; }

  /** 时间戳 → 日键 'YYYY-MM-DD'（本地时区；月份 0 起——v837 三连教训） */
  function dayKeyFromTs(ts) {
    var d = new Date((typeof ts === 'number' && isFinite(ts)) ? ts : Date.now());
    if (isNaN(d.getTime())) return null;
    return d.getFullYear() + '-' + pad2(d.getMonth() + 1) + '-' + pad2(d.getDate());
  }

  /** 日键合法性（字符串形态严格校验——normalizeBook/normalizeProgress 共用） */
  function isDayKey(k) {
    if (typeof k !== 'string' || !/^\d{4}-\d{2}-\d{2}$/.test(k)) return false;
    var p = k.split('-'), y = +p[0], m = +p[1], d = +p[2];
    return y >= 1970 && y <= 9999 && m >= 1 && m <= 12 && d >= 1 && d <= 31;
  }

  /** 日键加 n 天（本地 Date 构造规避 Date.parse 时区漂移） */
  function addDays(key, n) {
    if (!isDayKey(key)) return null;
    var p = key.split('-');
    var d = new Date(+p[0], +p[1] - 1, +p[2]);
    d.setDate(d.getDate() + n);
    return d.getFullYear() + '-' + pad2(d.getMonth() + 1) + '-' + pad2(d.getDate());
  }

  function emptyBook() { return { v: 1, items: {} }; }

  /**
   * 错题本条目：{ s(阶), due, wrong(累计答错次数), born(首次错日), last(最近练习日) }。
   * 记错题：阶归零、due=今日（当日重现——word applyGrade unknown 分支同构）。
   */
  function addWrong(book, qid, todayKey) {
    if (!book || typeof book !== 'object' || !book.items || typeof book.items !== 'object') return false;
    var id = typeof qid === 'string' ? qid.trim() : '';
    if (!id || !isDayKey(todayKey)) return false;
    var e = book.items[id] || { s: 0, wrong: 0, born: todayKey };
    e.s = 0;
    e.due = todayKey;
    e.wrong = (e.wrong || 0) + 1;
    e.born = isDayKey(e.born) ? e.born : todayKey;
    e.last = todayKey;
    book.items[id] = e;
    return true;
  }

  /**
   * 错题评分（复习队列三键同构 word-core applyGrade）：
   *   知道了(know) → 阶+1（封顶 INTERVALS.length），due=今日+INTERVALS[阶]；
   *     已在顶阶再答对 → 消账（从错题本移除，「错题本会清空」语义）。
   *   记错了(unknown)/模糊(fuzzy) → 阶归零、due=今日/明日。
   * 题目不在错题本时先按记错补档（防御：直接在错题模式答题）。
   */
  function applyWrongGrade(book, qid, grade, todayKey) {
    if (!book || typeof book !== 'object' || !book.items || !isDayKey(todayKey)) return 'noop';
    var id = typeof qid === 'string' ? qid.trim() : '';
    if (!id) return 'noop';
    var e = book.items[id];
    if (!e) {
      e = { s: 0, due: todayKey, wrong: 0, born: todayKey, last: todayKey };
      book.items[id] = e;
    }
    e.last = todayKey;
    var g = (grade === 'know' || grade === 'unknown' || grade === 'fuzzy') ? grade : 'fuzzy';
    if (g === 'know') {
      if (e.s >= INTERVALS.length - 1) {
        delete book.items[id];
        return 'cleared';
      }
      e.due = addDays(todayKey, INTERVALS[e.s]);
      e.s = Math.min(e.s + 1, INTERVALS.length - 1);
      return 'ok';
    }
    e.s = 0;
    e.due = g === 'unknown' ? todayKey : addDays(todayKey, 1);
    return 'ok';
  }

  /** 今日到期错题队列（due ≤ 今日，due 升序 + id 升序——同日重开队列稳定） */
  function dueWrong(book, todayKey) {
    var out = [];
    if (!book || typeof book !== 'object' || !book.items) return out;
    Object.keys(book.items).forEach(function (id) {
      var e = book.items[id];
      if (e && isDayKey(e.due) && e.due <= todayKey) out.push(id);
    });
    out.sort(function (a, b) {
      var ea = book.items[a], eb = book.items[b];
      if (ea.due !== eb.due) return ea.due < eb.due ? -1 : 1;
      return a < b ? -1 : 1;
    });
    return out;
  }

  /** 错题本归一（损坏 JSON/类型漂移静默降级——word normalizeProgress 同律） */
  function normalizeBook(raw) {
    var out = emptyBook();
    if (raw == null) return out;
    if (typeof raw === 'string') {
      try { raw = JSON.parse(raw); } catch (e) { return out; }
    }
    if (typeof raw !== 'object' || Array.isArray(raw)) return out;
    var items = (typeof raw.items === 'object' && raw.items && !Array.isArray(raw.items)) ? raw.items : {};
    var keys = Object.keys(items);
    for (var i = 0; i < keys.length && out.items && Object.keys(out.items).length < WRONG_MAX; i++) {
      var id = keys[i], e = items[id];
      if (typeof id !== 'string' || !id.trim() || id.length > 64) continue;
      if (!e || typeof e !== 'object' || Array.isArray(e)) continue;
      if (!Number.isInteger(e.s) || e.s < 0 || e.s >= INTERVALS.length) continue;
      if (!Number.isInteger(e.wrong) || e.wrong < 1) continue;
      if (!isDayKey(e.due) || !isDayKey(e.born)) continue;
      out.items[id.trim()] = {
        s: e.s, due: e.due, wrong: e.wrong, born: e.born,
        last: isDayKey(e.last) ? e.last : null,
      };
    }
    return out;
  }

  // ---------- 练习进度（每题对错计数 + 顺序游标） ----------
  function emptyProgress() { return { v: 1, stats: {}, cursor: {} }; }

  /** 记录一次作答：stats[qid] = { n(答题次数), ok(答对次数), last(ISO 日键) } */
  function bumpProgress(progress, qid, ok, todayKey) {
    if (!progress || typeof progress !== 'object') return false;
    if (!progress.stats || typeof progress.stats !== 'object') return false;
    var id = typeof qid === 'string' ? qid.trim() : '';
    if (!id || typeof ok !== 'boolean' || !isDayKey(todayKey)) return false;
    var e = progress.stats[id] || { n: 0, ok: 0 };
    e.n++;
    if (ok) e.ok++;
    e.last = todayKey;
    progress.stats[id] = e;
    return true;
  }

  /** 顺序练习游标：某科目当前推进到第几题（0 基），越界回落 0 */
  function seqCursor(progress, s, bankLen) {
    if (!progress || typeof progress !== 'object' || !progress.cursor) return 0;
    var v = progress.cursor[String(s)];
    var len = (typeof bankLen === 'number' && bankLen > 0) ? bankLen : 0;
    if (typeof v !== 'number' || !isFinite(v) || v < 0 || v % 1 !== 0) return 0;
    if (len && v >= len) return 0;
    return v;
  }

  /** 写入顺序游标（完成一题后推进；仅顺序模式调用） */
  function setSeqCursor(progress, s, idx) {
    if (!progress || typeof progress !== 'object') return;
    if (!progress.cursor || typeof progress.cursor !== 'object') progress.cursor = {};
    if (typeof idx !== 'number' || !isFinite(idx) || idx < 0 || idx % 1 !== 0) idx = 0;
    progress.cursor[String(s)] = Math.floor(idx);
  }

  /** 练习进度归一（损坏降级） */
  function normalizeProgress(raw) {
    var out = emptyProgress();
    if (raw == null) return out;
    if (typeof raw === 'string') {
      try { raw = JSON.parse(raw); } catch (e) { return out; }
    }
    if (typeof raw !== 'object' || Array.isArray(raw)) return out;
    var stats = (typeof raw.stats === 'object' && raw.stats && !Array.isArray(raw.stats)) ? raw.stats : {};
    Object.keys(stats).forEach(function (id) {
      var e = stats[id];
      if (typeof id !== 'string' || !id.trim() || id.length > 64) return;
      if (!e || typeof e !== 'object' || Array.isArray(e)) return;
      if (!Number.isInteger(e.n) || e.n < 1 || e.n > 99999) return;
      if (!Number.isInteger(e.ok) || e.ok < 0 || e.ok > e.n) return;
      var item = { n: e.n, ok: e.ok };
      if (isDayKey(e.last)) item.last = e.last;
      out.stats[id.trim()] = item;
    });
    var cursor = (typeof raw.cursor === 'object' && raw.cursor && !Array.isArray(raw.cursor)) ? raw.cursor : {};
    Object.keys(cursor).forEach(function (k) {
      if (k !== '1' && k !== '4') return;
      var v = cursor[k];
      if (typeof v === 'number' && isFinite(v) && v >= 0 && v % 1 === 0) out.cursor[k] = Math.floor(v);
    });
    return out;
  }

  // ---------- 偏好与模拟考在途状态归一 ----------
  /** 偏好（上次科目/模式——恢复到上次刷题现场，不自动开考） */
  function normalizeState(raw) {
    var out = { subject: 1, mode: MODES.SEQ };
    if (raw == null) return out;
    if (typeof raw === 'string') {
      try { raw = JSON.parse(raw); } catch (e) { return out; }
    }
    if (typeof raw !== 'object' || Array.isArray(raw)) return out;
    if (raw.subject === 1 || raw.subject === 4 || raw.subject === '1' || raw.subject === '4') {
      out.subject = Number(raw.subject);
    }
    var m = raw.mode;
    if (m === MODES.SEQ || m === MODES.RANDOM || m === MODES.EXAM || m === MODES.WRONG) out.mode = m;
    return out;
  }

  /**
   * 模拟考在途状态归一（重载续考：墙钟 startTs 不重置 → 时间不漂移不重置）。
   * { subject, startTs, idx, answers, picked[]（multi 暂选）} 任意畸形 → null（不开考）。
   */
  function normalizeExamState(raw) {
    if (raw == null) return null;
    if (typeof raw === 'string') {
      try { raw = JSON.parse(raw); } catch (e) { return null; }
    }
    if (typeof raw !== 'object' || Array.isArray(raw)) return null;
    if (raw.subject !== 1 && raw.subject !== 4) return null;
    var startTs = raw.startTs;
    if (typeof startTs !== 'number' || !isFinite(startTs) || startTs <= 0) return null;
    var idx = raw.idx;
    if (typeof idx !== 'number' || !isFinite(idx) || idx < 0 || idx % 1 !== 0) return null;
    var answers = raw.answers;
    if (!Array.isArray(answers) || answers.length > 200) return null;
    for (var i = 0; i < answers.length; i++) {
      var a = answers[i];
      if (a === null || a === undefined) { answers[i] = null; continue; }
      if (typeof a === 'number' && isFinite(a) && a >= 0 && a < 4 && a % 1 === 0) continue;
      if (Array.isArray(a) && a.length >= 2 && a.length <= 4 &&
          a.every(function (x) { return typeof x === 'number' && x >= 0 && x < 4; })) continue;
      answers[i] = null;
    }
    var picked = raw.picked;
    if (!Array.isArray(picked) || picked.length > 200) picked = [];
    picked = picked.map(function (p) {
      if (typeof p === 'number' && isFinite(p) && p >= 0 && p < 4 && p % 1 === 0) return Math.floor(p);
      return -1;
    });
    return {
      subject: raw.subject,
      startTs: startTs,
      idx: Math.floor(idx),
      answers: answers,
      picked: picked,
    };
  }

  // ---------- 历史成绩 ----------
  /** 记录成绩：{ 1: {best, last, at}, 4: {...} }（best 为分数） */
  function recordScore(scores, s, score, atTs) {
    if (!scores || typeof scores !== 'object') return false;
    if (s !== 1 && s !== 4) return false;
    if (typeof score !== 'number' || !isFinite(score) || score < 0) return false;
    var slot = scores[String(s)];
    if (!slot || typeof slot !== 'object' || Array.isArray(slot)) {
      slot = { best: -1, last: -1, at: 0 };
    }
    slot.last = Math.floor(score);
    if (score > slot.best) slot.best = Math.floor(score);
    slot.at = (typeof atTs === 'number' && isFinite(atTs)) ? atTs : Date.now();
    scores[String(s)] = slot;
    return true;
  }

  function normalizeScores(raw) {
    var out = {};
    if (raw == null) return out;
    if (typeof raw === 'string') {
      try { raw = JSON.parse(raw); } catch (e) { return out; }
    }
    if (typeof raw !== 'object' || Array.isArray(raw)) return out;
    [1, 4].forEach(function (s) {
      var slot = raw[String(s)];
      if (!slot || typeof slot !== 'object' || Array.isArray(slot)) return;
      if (typeof slot.best !== 'number' || !isFinite(slot.best) || slot.best < 0 || slot.best > 200) return;
      if (typeof slot.last !== 'number' || !isFinite(slot.last) || slot.last < 0 || slot.last > 200) return;
      out[String(s)] = {
        best: Math.floor(slot.best), last: Math.floor(slot.last),
        at: (typeof slot.at === 'number' && isFinite(slot.at) && slot.at > 0) ? slot.at : 0,
      };
    });
    return out;
  }

  // ---------- 深链（BUS_DELIVER driving/open） ----------
  /**
   * { subject: 1|4, mode: seq|random|exam|wrong } → 归一载荷；其余 null（不半解析）。
   * subject 缺省 1、mode 缺省 seq：显式提供但非法 → 整体 null（深链消费端提示）。
   */
  function parseDeepLink(payload) {
    if (!payload || typeof payload !== 'object' || Array.isArray(payload)) return null;
    var hasSub = 'subject' in payload;
    var hasMode = 'mode' in payload;
    var subject = 1, mode = MODES.SEQ;
    if (hasSub) {
      if (payload.subject === 1 || payload.subject === '1') subject = 1;
      else if (payload.subject === 4 || payload.subject === '4') subject = 4;
      else return null;
    }
    if (hasMode) {
      if (payload.mode === MODES.SEQ || payload.mode === MODES.RANDOM ||
          payload.mode === MODES.EXAM || payload.mode === MODES.WRONG) mode = payload.mode;
      else return null;
    }
    return { subject: subject, mode: mode, explicit: hasSub || hasMode };
  }

