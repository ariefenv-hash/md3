def validate():
    errs = []
    ids = set()
    for i, item in enumerate(Q):
        n = f'#{i+1}'
        if item['s'] not in (1, 4): errs.append(f'{n} 科目非法: {item["s"]}')
        if item['t'] not in ('j', 's', 'm'): errs.append(f'{n} 题型非法: {item["t"]}')
        if not item['q'] or len(item['q']) < 6: errs.append(f'{n} 题干过短')
        if len(item['exp']) < 8: errs.append(f'{n} 解析过短: {item["exp"][:12]}')
        if item['img'] is not None and item['img'] not in SIGN_KEYS:
            errs.append(f'{n} img 不在 SIGN_KEYS: {item["img"]}')
        if item['t'] == 's':
            if not item['o'] or not (2 <= len(item['o']) <= 4): errs.append(f'{n} 单选选项数非法')
            elif not all(isinstance(x, str) and x for x in item['o']): errs.append(f'{n} 单选选项空')
            elif not isinstance(item['a'], int) or not (0 <= item['a'] < len(item['o'])): errs.append(f'{n} 单选答案越界')
        elif item['t'] == 'm':
            if not item['o'] or not (3 <= len(item['o']) <= 4): errs.append(f'{n} 多选选项数非法')
            elif not all(isinstance(x, str) and x for x in item['o']): errs.append(f'{n} 多选选项空')
            else:
                a = item['a']
                if not isinstance(a, list) or len(a) < 2 or len(set(a)) != len(a) \
                   or not all(isinstance(x, int) and 0 <= x < len(item['o']) for x in a) \
                   or sorted(a) != a:
                    errs.append(f'{n} 多选答案非法: {a}')
        else:  # judge
            if item['a'] not in (0, 1): errs.append(f'{n} 判断答案非法: {item["a"]}')
    counts = {1: sum(1 for x in Q if x['s'] == 1), 4: sum(1 for x in Q if x['s'] == 4)}
    if counts[1] < 100: errs.append(f'科目一题量不足模拟考需求: {counts[1]} < 100')
    if counts[4] < 50: errs.append(f'科目四题量不足模拟考需求: {counts[4]} < 50')
    total = counts[1] + counts[4]
    return errs, counts, total

def emit_js():
    lines = ['  var BANK = [']
    for i, item in enumerate(Q):
        tid = f'D{i+1:03d}'
        jtype = {'j': 'judge', 's': 'single', 'm': 'multi'}[item['t']]
        if item['t'] == 'j':
            opts = ['正确', '错误']
            ans = 1 if item['a'] is False else 0   # True→0(正确) False→1(错误)
        else:
            opts = item['o']
            ans = item['a']
        seg = [f"{{ id:'{tid}', s:{item['s']}, cat:{json.dumps(item['cat'], ensure_ascii=False)}, type:'{jtype}', q:{json.dumps(item['q'], ensure_ascii=False)}"]
        seg.append(f"opts:[{','.join(json.dumps(o, ensure_ascii=False) for o in opts)}]")
        seg.append(f"ans:{json.dumps(ans)}" if item['t'] == 'm' else f"ans:{ans}")
        seg.append(f"exp:{json.dumps(item['exp'], ensure_ascii=False)}")
        if item['img']:
            seg.append(f"img:{json.dumps(item['img'])}")
        lines.append('    ' + ', '.join(seg) + ' },')
    lines.append('  ];')
    return '\n'.join(lines)

