    print(f'题库校验通过：共 {total} 题（科目一 {counts[1]} / 科目四 {counts[4]}），标志图题 {sum(1 for x in Q if x["img"])} 道，多选 {sum(1 for x in Q if x["t"]=="m")} 道')

    with open(CORE, encoding='utf-8') as f:
        src = f.read()
    begin = '  // ===== BANK-BEGIN（scripts/gen-driving-bank.py 生成·勿手改） ====='
    end = '  // ===== BANK-END ====='
    bi = src.find(begin); ei = src.find(end)
    if bi < 0 or ei < 0 or ei < bi:
        print(f'FAIL driving-core.js 缺少 BANK 标记 (bi={bi}, ei={ei})')
